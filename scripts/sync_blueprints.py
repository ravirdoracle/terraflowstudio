#!/usr/bin/env python3
"""Render the shared modules from this app into the odb-terraform-blueprints repo.

The app's templates are the master copy. Each cloud's ``clouds/<cloud>/blueprint.py``
names the modules the blueprints share; this renders them through the real
generator - so a blueprint gets exactly what an app user downloads - and writes
them, with a "generated, edit in the app" header, into ``db-at-<cloud>/modules/``.
Roots are not touched: each side keeps its own hand-written root.

    python scripts/sync_blueprints.py            write changed modules
    python scripts/sync_blueprints.py --check    exit 1 if the blueprints are stale
    python scripts/sync_blueprints.py --commit   write, then commit ONLY those files
                                                 in the blueprints repo

The blueprints repo is found at $TERRAFLOW_BLUEPRINTS, else ../odb-terraform-blueprints.

A target file is overwritten only when it is clean in the blueprints repo (matches
its HEAD) or already equals the render. Anything else is a hand edit made in the
blueprints - the sync stops and writes nothing rather than lose it.
"""
import argparse
import os
import subprocess
import sys

APP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, APP)

#: Clouds whose modules are shared. Azure is not: the app still emits one module
#: per instance, the blueprint a for_each module.
CLOUDS = ('aws', 'gcp')
FILES = ('main.tf', 'variables.tf', 'outputs.tf')
HEADER = (
    "# GENERATED by Terraflow Studio from clouds/{cloud}/templates/{template}/{file}.j2\n"
    "# Do not edit here: edit the template in odb_terraform_app. Its post-commit\n"
    "# hook re-renders this file and commits it to this repo.\n\n"
)


def blueprints_repo():
    return os.path.abspath(os.environ.get('TERRAFLOW_BLUEPRINTS')
                           or os.path.join(APP, '..', 'odb-terraform-blueprints'))


def rendered():
    """{blueprint-relative path: content} for every shared module file."""
    import importlib
    out = {}
    for cloud in CLOUDS:
        bp = importlib.import_module(f'clouds.{cloud}.blueprint')
        # The cloud's own generator, not app.generate_all: importing app also
        # starts the storage backend, which a sync has no use for.
        generate = getattr(importlib.import_module(f'clouds.{cloud}.generator'), f'generate_{cloud}_tf')
        files = generate(bp.PAYLOAD)
        for app_dir, (bp_dir, template) in bp.MODULES.items():
            for f in FILES:
                body = files.get(f'modules/{app_dir}/{f}')
                if body is None:
                    raise SystemExit(f'{cloud}: the generator emitted no modules/{app_dir}/{f} '
                                     f'for clouds/{cloud}/blueprint.py PAYLOAD')
                out[f'{bp.BLUEPRINT_DIR}/modules/{bp_dir}/{f}'] = (
                    HEADER.format(cloud=cloud, template=template, file=f) + body.rstrip('\n') + '\n')
    return out


def _git(repo, *args, check=True):
    r = subprocess.run(['git', '-C', repo, *args], capture_output=True, text=True,
                       encoding='utf-8', errors='replace')
    if check and r.returncode:
        raise SystemExit(f'git {" ".join(args)} failed in {repo}:\n{r.stderr.strip()}')
    return r.stdout


def _norm(text):
    return text.replace('\r\n', '\n')


def _read(path):
    try:
        with open(path, encoding='utf-8', newline='') as fh:
            return fh.read()
    except FileNotFoundError:
        return None


def plan(repo):
    """(to_write {path: content}, blocked [path]) for the current render."""
    to_write, blocked = {}, []
    for rel, content in rendered().items():
        current = _read(os.path.join(repo, rel))
        if current is not None and _norm(current) == content:
            continue                       # already up to date
        head = _git(repo, 'show', f'HEAD:{rel}', check=False)
        clean = current is None or _norm(current) == _norm(head)
        if not clean:
            blocked.append(rel)
        else:
            to_write[rel] = content
    return to_write, blocked


def _busy(repo):
    git_dir = _git(repo, 'rev-parse', '--git-dir').strip()
    git_dir = git_dir if os.path.isabs(git_dir) else os.path.join(repo, git_dir)
    return [s for s in ('MERGE_HEAD', 'rebase-merge', 'rebase-apply', 'CHERRY_PICK_HEAD')
            if os.path.exists(os.path.join(git_dir, s))]


def write(repo, to_write):
    for rel, content in to_write.items():
        path = os.path.join(repo, rel)
        existing = _read(path)
        # Keep the file's own line endings so the working tree shows no noise.
        if existing is not None and '\r\n' in existing:
            content = content.replace('\n', '\r\n')
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8', newline='') as fh:
            fh.write(content)


def commit(repo, paths, message):
    """Commit exactly these paths; anything else staged or modified is left alone."""
    _git(repo, 'add', '--', *paths)
    staged = [p for p in _git(repo, 'diff', '--cached', '--name-only', '--', *paths).split('\n') if p]
    if not staged:
        return None
    _git(repo, 'commit', '-q', '-m', message, '--', *staged)
    return _git(repo, 'rev-parse', '--short', 'HEAD').strip()


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--check', action='store_true', help='exit 1 if any shared module is stale')
    ap.add_argument('--commit', action='store_true', help='commit the synced files in the blueprints repo')
    ap.add_argument('--source-commit', default='', help='app commit to name in the message (the hook passes HEAD)')
    ap.add_argument('--quiet', action='store_true', help='print only what was committed, and errors')
    args = ap.parse_args(argv)

    repo = blueprints_repo()
    if not os.path.isdir(os.path.join(repo, '.git')):
        print(f'sync_blueprints: no git repo at {repo} (set TERRAFLOW_BLUEPRINTS)', file=sys.stderr)
        return 2

    to_write, blocked = plan(repo)
    rendered_paths = sorted(rendered())
    if args.check:
        stale = sorted(set(to_write) | set(blocked))
        for p in stale:
            print(f'stale: {p}')
        return 1 if stale else 0

    if blocked:
        print('sync_blueprints: these files were edited by hand in the blueprints repo and '
              'differ from the render - nothing written:', file=sys.stderr)
        for p in blocked:
            print(f'  {p}', file=sys.stderr)
        print('Move the change into the app template (the master copy), or discard it there, '
              'then sync again.', file=sys.stderr)
        return 3

    write(repo, to_write)
    if not args.quiet:
        for p in sorted(to_write):
            print(f'synced: {p}')

    if args.commit:
        busy = _busy(repo)
        if busy:
            print(f'sync_blueprints: blueprints repo is mid-{busy[0]}; files written, not committed.',
                  file=sys.stderr)
            return 4
        subject, sha = 'sync shared modules', ''
        if args.source_commit:
            subject = _git(APP, 'log', '-1', '--format=%s', args.source_commit).strip()
            sha = _git(APP, 'rev-parse', '--short', args.source_commit).strip()
        message = (f'sync: {subject}\n\n'
                   f'Rendered from odb_terraform_app{" " + sha if sha else ""} by '
                   f'scripts/sync_blueprints.py. The app templates are the master copy\n'
                   f'of these modules; edit them there.\n')
        # Every rendered path, not just the ones written this run: a file synced
        # earlier but never committed is committed now.
        done = commit(repo, rendered_paths, message)
        if done:
            print(f'blueprints: committed {done} in {repo}')
        elif not args.quiet:
            print('blueprints already up to date - nothing to commit')
    return 0


if __name__ == '__main__':
    sys.exit(main())
